/** 生き物の種類。表に初めからある37種と、探索の途中で足される種類（主・王の影・忘れられた獣・試しの間の的）が持つ欄 */
export interface MonsterType {
  /** 地図に出る文字 */
  ch: string;
  name: string;
  col: Color;
  /** 灯りの色（体の色と違う時。火と氷の猟犬） */
  lcol?: Color;
  /** 形（bodies の組み立てを選ぶ） */
  form: string;
  scale: number;
  speed: number;
  /** 浮く高さ */
  fl: number;
  /** 灯りの強さ */
  light: number;
  /** 光の尾の長さ */
  trail: number;
  /** 見た時の様子（起きている時。探索の中で初めて見た時の伝言と、図鑑の説明） */
  verb: string;
  /** 小さな生き物の役目（fish・grazer・shrieker・mimic・cleaner・engineer） */
  critter?: string;
  aquatic?: boolean;
  spider?: boolean;
  /** 猟犬の種類（fire・ice・light） */
  hound?: string;
  snap?: boolean;
  watcher?: boolean;
  /** 住む所（bog・amph・lava・deep） */
  habitat?: string;
  heavy?: boolean;
  golem?: boolean;
  dragon?: boolean;
  lich?: boolean;
  hop?: boolean;
  conj?: boolean;
  flier?: boolean;
  peaceful?: boolean;
  invisible?: boolean;
  /** 見た目（形の上に足す特徴。人型・四つ足・死者・主。src/lib/bodies/build.ts の addLooks が足し、人型の主は元の生き物から引き継ぐ） */
  look?: string | null | undefined;
  /** ここから下は、探索の途中で足される種類（その階の主 lord・王の影 final・忘れられた獣 X と図鑑の見本・試しの間の的）だけが持つ欄 */
  /** 主：元の生き物の記号（王の影は 'final'） */
  sk?: string;
  /** 主と王の影 */
  boss?: boolean;
  /** 忘れられた獣（src/lib/bodies/lords.ts の makeBeastType） */
  beast?: boolean;
  /** 忘れられた獣の体の作り（翼・脚・目など） */
  spec?: BeastBody;
  /** 忘れられた獣の言い伝え */
  lore?: string;
  /** 試しの間の的 */
  dummy?: boolean;
  /** 支道の主（主の祭壇を残す） */
  lord?: boolean;
}

